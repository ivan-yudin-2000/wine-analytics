-- Гипотеза: чем старше вино, тем выше оценка
--
-- Возраст = 2017 − год урожая (vintage_year). 2017 — год сбора данных и самый поздний урожай в базе.
-- Вина без года урожая (NV — смесь разных лет) не учитываем.
--
-- Запрос 1 — сила связи (115 645 вин с годом урожая):
--   возраст и оценка     −0.05
--
-- Запрос 2 — оценки по возрастным группам:
--   Возраст          Вин      Средняя оценка   Средняя цена
--   до 3 лет         12 264   88.3             $24
--   3–5 лет          42 657   88.9             $36
--   6–10 лет         45 877   88.3             $37
--   11–20 лет        14 623   88.2             $40
--   больше 20 лет       224   89.8             $101
--
-- Вывод: гипотеза не подтвердилась. Связи между возрастом и оценкой практически нет
-- (r = −0.05): средняя оценка во всех группах до 20 лет почти одинаковая, 88.2–88.9.
-- Исключение — вина старше 20 лет (89.8), но их всего 224, и они в среднем дорогие ($101):
-- скорее всего, это особые вина для долгой выдержки, и высокая оценка может объясняться
-- ценой (см. анализ 01), а не возрастом.
--
-- Ограничения:
-- - в датасете нет даты дегустации, поэтому возраст считается на 2017 год,
--   а не на момент оценки;
-- - у 4 вин NV число в названии — год основания марки, а не урожая
--   (например, «Arthur Metz NV 1904»), на результат это не влияет.


-- 1. Сила связи возраста и оценки
SELECT
    CORR(2017 - vintage_year, points) AS r_age_points,
    COUNT(*)                          AS wines_with_year
FROM wines
WHERE vintage_year IS NOT NULL;


-- 2. Оценки по возрастным группам
SELECT
    CASE
        WHEN 2017 - vintage_year <= 2  THEN '1. до 3 лет'
        WHEN 2017 - vintage_year <= 5  THEN '2. 3–5 лет'
        WHEN 2017 - vintage_year <= 10 THEN '3. 6–10 лет'
        WHEN 2017 - vintage_year <= 20 THEN '4. 11–20 лет'
        ELSE                                '5. больше 20 лет'
    END                            AS age_group,
    COUNT(*)                       AS wines,
    ROUND(AVG(points)::numeric, 1) AS avg_points,
    ROUND(AVG(price)::numeric, 0)  AS avg_price
FROM wines
WHERE vintage_year IS NOT NULL
GROUP BY age_group
ORDER BY age_group;
